// Incremental for loop
console.log("Incremental For Loop:");
for(let i = 0; i <= 10; i++){
    console.log(i);
}

// decremental for loop
console.log("Decremental For Loop - 1:");
for(let i = 10; i >= 0; i--){
    console.log(i);
}

// Decremental for loop:
console.log("Decremental For Loop - 2:");
for(let i = 20; i >= 11; i--){
    console.log(i);
}